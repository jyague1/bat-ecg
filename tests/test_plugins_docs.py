"""Tests for :func:`bat.plugins.docs.generate_docs` (CARD-018).

Uses the same on-disk local-plugins-directory + ``ModuleSchema`` fixture
pattern established in ``tests/test_cli_plugins.py`` /
``tests/test_plugins_discovery.py``: write small plugin module files under a
real ``plugins/`` directory, run discovery (CARD-006) against it to build a
real registry, then call ``generate_docs`` directly on that registry.
"""

